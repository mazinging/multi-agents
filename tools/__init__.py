"""
tools/__init__.py —— 工具包
================================================================================
【工具（Tool）在 Agent 架构里的角色】
    ReAct 循环里的 "Action" 就是调用一个工具。
    工具是 Agent 与外部世界（知识库、计算、API）交互的唯一通道。

    Agent 的"智能"体现在【决定调哪个工具、传什么参数】，
    而"工具"负责【可靠地执行并返回结构化结果】。

【本项目工具设计的四条原则（每一条都影响 Agent 的成功率）】

    1. 工具名要自解释
       `search_local_docs` 比 `q1` 好得多。模型只靠名字就能猜出用途，
       prompt 里也不用额外解释。命名本身就是 prompt 的一部分。

    2. 参数要少、要简单
       参数越多，模型填错的概率越高。能用 1 个参数就不要用 3 个。
       本项目所有工具都只接受一个字符串参数，就是为了把出错的
       可能性降到最低。这是"为模型设计接口"而非"为人设计接口"的思路。

    3. 返回值要结构化 + 带上下文
       不要返回裸数据。返回时带上 doc_id、分数、说明，
       让模型能据此判断"这个结果可靠吗、要不要继续查"。
       模型看到的不是数据，是"信息的呈现方式"。

    4. 错误信息要能指导模型自我纠正
       这是最容易被忽视的一条。返回 `KeyError: 'doc_id'` 对模型毫无帮助；
       返回"未找到文档 auto，可用文档有：01_xxx, 02_yyy，请重新选择"
       则能让模型在下一轮自动修正。错误信息是给模型的提示。

【统一接口设计】
    所有工具都实现 BaseTool，通过 ToolRegistry 注册。
    Agent 只依赖注册表，不依赖具体工具 —— 这样加新工具不用改 Agent 代码。
================================================================================
"""

